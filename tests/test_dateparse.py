def test_find_candidates_returns_scores():
    texts = ["제조 2025.01.05", "유통기한 2026.01.04 까지"]
    cands = [c for t in texts for c in find_candidates(t)]
    by_year = {c.y: c for c in cands}
    assert 2025 in by_year and 2026 in by_year
    assert by_year[2026].score > by_year[2025].score
